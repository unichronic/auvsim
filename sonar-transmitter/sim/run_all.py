# ---- firmware tables ----------------------------------------------------------
def write_headers(reg, fs, outdir):
    d = os.path.join(outdir, "firmware")
    os.makedirs(d, exist_ok=True)
    groups = {"lfm": [], "geo": [], "barker13": [], "lfm_centres": []}
    for name in reg:
        g = "lfm_centres" if name.startswith("lfm_c") else name.rsplit("_", 1)[0]
        groups[g].append(name)
    manifest = ["name,mod,window,fs_hz,n,duration_us,params,crc32"]
    for g, names in groups.items():
        path = os.path.join(d, f"sim0_{g}.h")
        L = ["// AUTO-GENERATED by sim/sim0/run_all.py -- do not edit by hand.",
             "// Sim-0 golden-reference DAC tables for the 8-bit R-2R ladder on GPIO16-23.",
             "// code = floor(128 + 127*x + 0.5), x = modulation * window in [-1,1].",
             "// Idle (between pulses) = 128. Full scale always: amplitude is set in analog",
             "// by the MCP41010, never by scaling these codes.",
             "// Tables are const (flash/XIP); copy to an SRAM buffer before DMA streaming.",
             "#pragma once", "#include <stdint.h>", "",
             f"#ifndef SIM0_FS_HZ\n#define SIM0_FS_HZ {int(fs)}u\n#endif",
             f"#if SIM0_FS_HZ != {int(fs)}u\n#error \"sim0 tables generated for a different sample rate\"\n#endif", ""]
        for name in names:
            x, codes, meta = reg[name]
            crc = zlib.crc32(codes.tobytes())
            params = " ".join(f"{k}={v:g}" if isinstance(v, float) else f"{k}={v}"
                              for k, v in meta.items() if k not in ("window", "fs", "n", "mod"))
            N = name.upper()
            L += [f"// {name}: {params} window={meta['window']} n={len(codes)} "
                  f"({len(codes) / fs * 1e6:.1f} us)",
                  f"#define SIM0_{N}_LEN {len(codes)}u",
                  f"#define SIM0_{N}_CRC32 0x{crc:08x}u  /* zlib/IEEE CRC-32 over the bytes */",
                  f"static const uint8_t SIM0_{N}[{len(codes)}] = {{"]
            for i in range(0, len(codes), 20):
                L.append("  " + ",".join(f"{v:3d}" for v in codes[i:i + 20]) + ",")
            L += ["};", ""]
            manifest.append(f"{name},{meta['mod']},{meta['window']},{int(fs)},{len(codes)},"
                            f"{len(codes) / fs * 1e6:.1f},{params},0x{crc:08x}")
        with open(path, "w") as fh:
            fh.write("\n".join(L))
        print("  wrote", path)
    with open(os.path.join(d, "tables_manifest.csv"), "w") as fh:
        fh.write("\n".join(manifest) + "\n")


# ---- metrics ------------------------------------------------------------------
def metrics(reg, fs):
    M = {"fs_hz": fs}
    # 1. window textbook sidelobes
    M["window_psl_db"] = {w: sim0.window_psl_db(w) for w in sim0.WINDOWS}

    # 2. quantisation: SQNR per table, plus the theoretical full-scale figure
    M["sqnr_theory_fullscale_sine_db"] = 6.02 * sim0.BITS + 1.76
    M["sqnr_db"] = {k: sim0.sqnr_db(x, c) for k, (x, c, _) in reg.items()}
    # digital amplitude scaling (the rejected alternative to analog amplitude control)
    tone = np.sin(2 * np.pi * 0.0331 * np.arange(20000) + 0.3)
    M["sqnr_vs_digital_scale_db"] = {f"{s:g}": sim0.sqnr_db(s * tone, sim0.quantise(s * tone))
                                     for s in (1, 0.5, 0.25, 0.125)}

    # 3. CW FFT floor (8192-pt), the "-86 dB" claim; and the exact-ratio tones
    M["cw_8192_noncoherent"] = dict(zip(("floor_per_bin_dbc", "worst_spur_dbc"),
                                        sim0.cw_floor(331 * fs / 8192, fs, 8192)))
    M["cw_exact_ratio_tones"] = {f"{int(f / 1e3)}k": dict(zip(("floor_per_bin_dbc", "worst_spur_dbc"),
                                                              sim0.cw_floor(f, fs, 8000)))
                                 for f in sim0.CENTRES}

    # 4. tone-burst sidelobes, ideal float vs 8-bit (does 8-bit keep Blackman's -58?)
    fc, T = 300e3, sim0.PULSE_T
    tb = {}
    for w in sim0.WINDOWS:
        s = np.sin(2 * np.pi * fc * np.arange(sim0.n_samples(T, fs)) / fs) * sim0.window(w, sim0.n_samples(T, fs))
        c = sim0.quantise(s)
        pi, fi = sim0.burst_sidelobes(w, sim0.AMP * s, fs, fc, T)
        pq, fq = sim0.burst_sidelobes(w, c.astype(float) - sim0.MID, fs, fc, T)
        tb[w] = dict(psl_ideal_db=pi, psl_8bit_db=pq, floor_ideal_db=fi, floor_8bit_db=fq)
    M["tone_burst_300k_500us"] = tb

    # 5. per-waveform: matched-filter PSLR, out-of-band level, 8-bit floor, first image
    wf = {}
    for k, (x, c, meta) in reg.items():
        ac = c.astype(float) - sim0.MID
        f, d = sim0.esd_db(ac, fs, nfft=1 << 18)
        fi_, di = sim0.esd_db(sim0.AMP * x, fs, nfft=1 << 18)
        fl = (f >= 1.5e6) & (f <= 0.9 * fs / 2)
        wf[k] = dict(
            pslr_matched_filter_db=sim0.autocorr_pslr_db(ac, fs, meta),  # on the 8-bit codes
            level_at_600kHz_db=float(np.interp(600e3, f, d)),
            floor_1p5M_up_8bit_db=float(10 * np.log10(np.mean(10 ** (d[fl] / 10)))),
            floor_1p5M_up_ideal_db=float(10 * np.log10(np.mean(10 ** (di[fl] / 10)))),
            first_image_db_butter=sim0.image_levels(c, fs, "butter"),
            first_image_db_raw=sim0.image_levels(c, fs, "none"),
        )
    M["waveforms"] = wf

    # 6. ZOH droop + filter, for 10 and 5 MS/s
    zf = {}
    for r in (sim0.FS, sim0.FS_FALLBACK):
        img = r - sim0.BAND[1]
        zf[f"{r / 1e6:g}MS/s"] = dict(
            zoh_droop_100k_db=float(sim0.zoh_db(100e3, r)),
            zoh_droop_500k_db=float(sim0.zoh_db(500e3, r)),
            image_freq_hz=img,
            zoh_image_rel_500k_db=float(sim0.zoh_db(img, r) - sim0.zoh_db(500e3, r)),
            butter_atten_image_db=float(20 * np.log10(abs(sim0.filter_response(img, "butter")))),
            equal_atten_image_db=float(20 * np.log10(abs(sim0.filter_response(img, "equal")))),
        )
        z = zf[f"{r / 1e6:g}MS/s"]
        z["total_image_rejection_butter_db"] = z["zoh_image_rel_500k_db"] + z["butter_atten_image_db"] \
            - float(20 * np.log10(abs(sim0.filter_response(500e3, "butter"))))
    M["zoh_filter"] = zf
    M["filter_passband_db"] = {kind: {f"{int(f / 1e3)}k": float(20 * np.log10(abs(sim0.filter_response(f, kind))))
                                      for f in (100e3, 200e3, 350e3, 500e3)}
                               for kind in ("butter", "equal")}
    return M


# ---- figures ------------------------------------------------------------------
def pad_ac(codes, fs, pre=20e-6, post=40e-6):
    c = np.concatenate([np.full(int(pre * fs), sim0.MID), codes, np.full(int(post * fs), sim0.MID)])
    return np.arange(len(c)) / fs - pre, c


def fig_waveforms(reg, fs, out):
    fig, ax = plt.subplots(3, 2, figsize=(13, 8), gridspec_kw={"width_ratios": [2.2, 1]})
    for i, (name, ttl) in enumerate((("lfm_hann", "LFM chirp 100→500 kHz"),
                                     ("geo_hann", "Geometric sweep 100→500 kHz"),
                                     ("barker13_hann", "Phase-coded: Barker-13 BPSK on 250 kHz"))):
        x, c, meta = reg[name]
        t, cc = pad_ac(c, fs)
        w = sim0.window("hann", len(c))
        a = ax[i, 0]
        a.step(t * 1e6, cc, where="post", color=C[0], lw=0.5)
        for sgn in (1, -1):
            a.plot(np.arange(len(c)) / fs * 1e6, sim0.MID + sgn * sim0.AMP * w, color=C[1], lw=1.2, ls="--",
                   label="Hann envelope" if sgn == 1 else None)
        a.set(ylim=(-5, 260), ylabel="DAC code (0–255)", title=f"{ttl} — Hann window, 8-bit codes")
        a.axhline(128, color=MUTED, lw=0.6)
        a.legend(loc="upper right")
        # zoom where the frequency is highest-ish
        a = ax[i, 1]
        t0 = meta["T"] * 0.75
        s = int(t0 * fs)
        seg = c[s:s + int(12e-6 * fs)]
        a.step((np.arange(len(seg)) / fs + t0) * 1e6, seg, where="post", color=C[0], lw=1)
        a.plot((np.arange(len(seg)) / fs + t0) * 1e6, seg, ".", color=C[0], ms=3)
        a.set(ylabel="DAC code", title=f"Zoom 12 µs: stair-steps = ZOH ({fs / 1e6:g} MS/s)")
    for a in ax[-1]:
        a.set_xlabel("Time (µs)")
    fig.suptitle(f"Sim-0: the three modulation types as the R-2R DAC will see them (fs = {fs / 1e6:g} MS/s)",
                 fontweight="bold")
    fig.tight_layout()
    save(fig, os.path.join(out, "fig1_waveforms.png"))


