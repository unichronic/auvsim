# ---- synthetic "measured" data --------------------------------------------------
def synthetic_measured(codes, fs, out, seed=58):
    """Predicted chain + plausible non-idealities, sampled like a 50 MS/s 8-bit
    scope. Clearly SYNTHETIC: exercises `compare` before any hardware exists."""
    rng = np.random.default_rng(seed)
    pre, post = 100e-6, 150e-6
    c = np.concatenate([np.full(int(pre * fs), sim0.MID), codes, np.full(int(post * fs), sim0.MID)]).astype(np.uint8)
    bits = (c[:, None] >> np.arange(8)) & 1
    weights = 2.0 ** np.arange(8) * (1 + rng.normal(0, 0.004, 8))     # 0.4 % bit-weight error
    lad = bits @ weights
    up = 5                                                             # 50 MS/s scope
    t, v, fa = sim0.analog(lad, fs, up=up, fc=680e3, pre=0, post=0)   # filter 3 % low
    v = 1.2 * v                                                        # op-amp gain
    v = v + 8e-4 * v ** 2 + 5e-4 * v ** 3                              # ~-62 dBc HD2, ~-66 dBc HD3
    v = 2.5 + v + rng.normal(0, 2e-3, len(v))                         # mid-rail + 2 mV rms noise
    lsb = 4.0 / 256                                                    # scope: 8-bit, 0.5 V/div x 8 div
    v = np.round((v - 2.5) / lsb) * lsb + 2.5
    t = t - pre + 3.7e-6                                              # scope trigger 3.7 us early
    tpath = os.path.join(out, "synthetic_measured_lfm_hann_time.csv")
    np.savetxt(tpath, np.column_stack([t, v]), delimiter=",", fmt="%.9g",
               header="SYNTHETIC -- NOT A MEASUREMENT. Generated by run_all.py to test compare.py.\n"
                      "time_s,voltage_v", comments="# ")
    print("  wrote", tpath)
    # analyser-style spectrum export: 3 kHz RBW, 0-5 MHz, 4001 points, dBm-ish absolute offset
    f, d = sim0.esd_db(v - v.mean(), fa, nfft=1 << 21)
    rbw = 3e3
    k = int(round(rbw / (f[1] - f[0])))
    lin = np.convolve(10 ** (d / 10), np.ones(k) / k, mode="same")
    fg = np.linspace(0, 5e6, 4001)
    dg = 10 * np.log10(np.interp(fg, f, lin) + 10 ** (-85 / 10) * rng.exponential(1, fg.size)) - 7.0
    spath = os.path.join(out, "synthetic_measured_lfm_hann_spectrum.csv")
    np.savetxt(spath, np.column_stack([fg, dg]), delimiter=",", fmt="%.6g",
               header="SYNTHETIC -- NOT A MEASUREMENT. Emulated analyser, RBW 3 kHz.\nfrequency_hz,level_dbm",
               comments="# ")
    print("  wrote", spath)
    return tpath, spath


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fs", type=float, default=sim0.FS)
    a = ap.parse_args()
    fs = a.fs
    out = os.path.join(HERE, "out") if fs == sim0.FS else os.path.join(HERE, "out", f"fs{fs / 1e6:g}M")
    os.makedirs(out, exist_ok=True)
    print(f"Sim-0 at fs = {fs / 1e6:g} MS/s -> {out}")
    reg = sim0.table_registry(fs)
    write_headers(reg, fs, out)
    M = metrics(reg, fs)
    fig_waveforms(reg, fs, out)
    fig_mod_spectra(reg, fs, out)
    fig_spectrograms(reg, fs, out)
    fig_windows(reg, fs, out, M)
    fig_quant(fs, out, M)
    fig_zoh(reg, fs, out)
    tpath, spath = synthetic_measured(reg["lfm_hann"][1], fs, out)
    M["synthetic_compare_time"] = compare(tpath, "lfm_hann", fs, out=out)
    M["synthetic_compare_spectrum"] = compare(spath, "lfm_hann", fs, rbw=3e3, out=out)
    with open(os.path.join(out, "metrics.json"), "w") as fh:
        json.dump(M, fh, indent=1, default=float)
    print("  wrote", os.path.join(out, "metrics.json"))
    summary(M)


