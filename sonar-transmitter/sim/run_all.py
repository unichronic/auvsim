def fig_quant(fs, out, M):
    fig, ax = plt.subplots(1, 3, figsize=(16, 4.6))
    a = ax[0]
    fc, T = 300e3, sim0.PULSE_T
    N = sim0.n_samples(T, fs)
    s = np.sin(2 * np.pi * fc * np.arange(N) / fs) * sim0.window("blackman", N)
    for i, (sig, lab) in enumerate(((sim0.quantise(s).astype(float) - sim0.MID, "8-bit quantised"),
                                    (sim0.AMP * s, "ideal (float)"))):
        f, d = sim0.esd_db(sig, fs, nfft=1 << 20, ref_band=(fc - 50e3, fc + 50e3))
        m = f <= fs / 2
        a.plot(f[m] / 1e6, d[m], color=C[i], lw=0.5 if i == 0 else 1.0, label=lab)
    tb = M["tone_burst_300k_500us"]["blackman"]
    a.axhline(-58.1, color=INK2, lw=1, ls="--", label="Blackman peak sidelobe, −58 dB")
    a.axhline(tb["floor_8bit_db"], color=C[2], lw=1.4, ls="-",
              label=f"8-bit floor, mean {tb['floor_8bit_db']:.0f} dB")
    a.set(title="Blackman 300 kHz burst (500 µs): 8-bit floor vs sidelobes", xlabel="Frequency (MHz)",
          ylabel="dB rel. peak", ylim=(-160, 5))
    legend_below(a)

    a = ax[1]
    for i, (ft, N, lab) in enumerate(((331 * fs / 8192, 8192, "%.1f kHz tone, 8192-pt FFT (non-periodic error)" % (331 * fs / 8192 / 1e3)),
                                      (500e3, 8000, "500 kHz tone: error periodic → harmonic spurs"))):
        c = sim0.quantise(np.sin(2 * np.pi * ft / fs * np.arange(N))).astype(float) - sim0.MID
        p = np.abs(np.fft.rfft(c)) ** 2
        d = 10 * np.log10(p / p.max() + 1e-30)
        f = np.fft.rfftfreq(N, 1 / fs) / 1e6
        if i == 0:
            a.plot(f, d, color=C[0], lw=0.3, alpha=0.7, label=lab)
        else:
            keep = d > -120
            a.plot(f[keep], d[keep], "o", color=C[1], ms=5, label=lab)
    a.axhline(M["cw_8192_noncoherent"]["floor_per_bin_dbc"], color=C[2], lw=1.4,
              label=f"simulated mean floor {M['cw_8192_noncoherent']['floor_per_bin_dbc']:.1f} dB")
    a.axhline(-86, color=INK2, lw=1, ls="--", label="docs' claim: −86 dB")
    a.set(title="Continuous full-scale tone, rectangular FFT, 8-bit", xlabel="Frequency (MHz)",
          ylabel="dB rel. carrier (per bin)", ylim=(-140, 5))
    legend_below(a, 1)

    a = ax[2]
    sc = M["sqnr_vs_digital_scale_db"]
    xs = list(sc)
    a.bar(range(len(xs)), [sc[k] for k in xs], color=C[0], width=0.6)
    for i, k in enumerate(xs):
        a.text(i, sc[k] + 0.8, f"{sc[k]:.1f} dB\n(≈{(sc[k] - 1.76) / 6.02:.1f} bits)", ha="center", fontsize=8)
    a.set_xticks(range(len(xs)), [f"{float(k) * 100:g}%" for k in xs])
    a.set(ylim=(0, 60), title="SQNR if amplitude were scaled digitally",
          xlabel="Digital amplitude (fraction of full scale)", ylabel="SQNR (dB)")
    a.grid(axis="x", visible=False)
    fig.suptitle("8-bit quantisation: where the floor actually sits", fontweight="bold")
    fig.tight_layout()
    save(fig, os.path.join(out, "fig5_quantisation.png"))


