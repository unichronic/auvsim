def fig_spectrograms(reg, fs, out):
    names = [f"lfm_c{int(f / 1e3)}k_hann" for f in sim0.CENTRES] + ["lfm_hann", "geo_hann", "barker13_hann"]
    titles = [f"LFM centred {int(f / 1e3)} kHz (±10%)" for f in sim0.CENTRES] + \
             ["LFM 100→500 kHz", "Geometric 100→500 kHz", "Barker-13 BPSK @ 250 kHz"]
    fig, ax = plt.subplots(2, 4, figsize=(16, 7.5))
    for a, name, ttl in zip(ax.flat, names, titles):
        x, c, meta = reg[name]
        t, cc = pad_ac(c, fs)
        f, tt, S = signal.spectrogram(cc.astype(float) - sim0.MID, fs, window="hann",
                                      nperseg=256, noverlap=240, mode="psd")
        S = 10 * np.log10(S / S.max() + 1e-12)
        m = f <= 800e3
        im = a.pcolormesh((tt + t[0]) * 1e6, f[m] / 1e3, S[m], vmin=-70, vmax=0, cmap="Blues",
                          shading="auto", rasterized=True)
        for b in sim0.BAND:
            a.axhline(b / 1e3, color=C[1], lw=0.8, ls="--")
        a.set(title=ttl, xlabel="Time (µs)", ylabel="Frequency (kHz)")
    ax.flat[-1].axis("off")
    ax.flat[-1].text(0.02, 0.6, "Dashed orange lines: 100 kHz and 500 kHz\nband edges.\n\n"
                     "8-bit codes, Hann window, fs = %g MS/s.\nSTFT: 256-pt Hann, 25.6 µs segments.\n"
                     "Colour: dB relative to panel peak." % (fs / 1e6), fontsize=10, color=INK2,
                     transform=ax.flat[-1].transAxes, va="top")
    fig.colorbar(im, ax=ax.flat[-1], location="bottom", fraction=0.08, label="dB")
    fig.suptitle("Predicted spectrograms: chirps at 100 / 200 / 350 / 500 kHz and the three modulation types",
                 fontweight="bold")
    fig.tight_layout()
    save(fig, os.path.join(out, "fig3_spectrograms.png"))


